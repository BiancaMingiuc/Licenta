"""Schemas for the surveillance journal."""

from datetime import datetime
from typing import Any, List, Optional

from pydantic import BaseModel, Field

from app.schemas.detection_schema import DetectionReason

UNKNOWN_PERSON_NAME = "Unknown Person"


class LogCreate(BaseModel):
    """One surveillance event.

    ``hub_id`` is present here for INTERNAL callers (the Edge AI loop on the
    Raspberry Pi builds this object directly). On the HTTP route the value
    supplied by the client is overwritten with the hub from the token, so a
    client cannot write into another hub's journal.

    ``timestamp`` is not accepted from the client: it is generated by the
    server, otherwise an audit journal could receive backdated events.

    ``status`` reuses ``DetectionReason`` rather than declaring its own list,
    so the journal cannot drift away from what the detection service produces.
    The default is the fail-loud one: an event whose reason was not stated is
    treated as an intruder, not as a known person.

    ``user_name`` is accepted but DERIVED on write: the service replaces it
    with the referenced person's name, with the placeholder for an
    unidentified person, or with NULL for a fault. A journal row that named
    someone other than the person it points at would read as evidence while
    being false.

    ``status`` and ``user_id`` must agree -- see
    ``describe_identity_conflict``. A row saying "INTRUDER" while naming a
    person is refused, because an intruder is by definition unidentified.
    """

    hub_id: str = "HUB_001"
    camera_id: str = "cam_entrance"
    user_id: Optional[str] = None
    user_name: Optional[str] = UNKNOWN_PERSON_NAME
    status: DetectionReason = "INTRUDER"


class LogEntity(BaseModel):
    """An event as returned by the API.

    ``snapshot_path`` is deliberately absent. The photo path has no place in a
    listing an ``APP_USER`` can read: intruder images are biometric data and
    are served separately, on a dedicated route restricted to ``ADMIN``. The
    client only needs to know WHETHER an image exists, so it can show an
    indicator.
    """

    id: str
    hub_id: str
    camera_id: str
    user_id: Optional[str] = None
    user_name: Optional[str] = UNKNOWN_PERSON_NAME
    status: str
    timestamp: Optional[datetime] = None
    has_snapshot: bool = False

    @classmethod
    def from_row(cls, row: dict[str, Any]) -> "LogEntity":
        return cls(
            id=row["id"],
            hub_id=row["hub_id"],
            camera_id=row["camera_id"],
            user_id=row.get("user_id"),
            user_name=row.get("user_name"),
            status=row["status"],
            timestamp=row.get("timestamp"),
            has_snapshot=bool(row.get("snapshot_path")),
        )


class LogPage(BaseModel):
    """One page of events plus the metadata needed to navigate.

    ``total`` lets the UI show the number of pages without downloading every
    record -- precisely the problem pagination solves.
    """

    items: List[LogEntity] = Field(default_factory=list)
    total: int
    limit: int
    offset: int


class SimulatedDetection(BaseModel):
    """Input of the simulation endpoint, used during development only."""

    camera_id: str = "cam_entrance"
    expected: bool = False
    user_id: Optional[str] = None
